#!/usr/bin/env bash
set -euo pipefail

THEME="${1:-}"
BASE="/home/tsilez"
WALLPAPER_ROOT="$BASE/Pictures/Wallpapers"
STATE_DIR="$BASE/.config/themes"
STATE_FILE="$STATE_DIR/current-theme"
COLORS_FILE="$BASE/.config/polybar/theme-colors.ini"
ROFI_COLORS="$BASE/.config/rofi/theme-colors.rasi"

case "${THEME,,}" in
  christian)
    THEME="Christian"
    ACCENT="#34C759"
    ;;
  motivational)
    THEME="Motivational"
    ACCENT="#FF9500"
    ;;
  sci-fi|sci_fi|scifi)
    THEME="Sci-Fi"
    ACCENT="#0A84FF"
    ;;
  *)
    echo "Usage: $0 Christian|Motivational|Sci-Fi" >&2
    exit 1
    ;;
esac

WALL_DIR="$WALLPAPER_ROOT/$THEME"

# Support the existing directory name "Sci-fi".
if [[ "$THEME" == "Sci-Fi" && ! -d "$WALL_DIR" ]]; then
  WALL_DIR="$WALLPAPER_ROOT/Sci-fi"
fi

if [[ ! -d "$WALL_DIR" ]]; then
  echo "Wallpaper folder not found: $WALL_DIR" >&2
  echo "Create it and add images before selecting this theme." >&2
  exit 1
fi

mapfile -d '' WALLPAPERS < <(
  find "$WALL_DIR" -maxdepth 1 -type f \
    \( -iname '*.jpg' -o -iname '*.jpeg' -o \
       -iname '*.png' -o -iname '*.webp' \) \
    -print0
)

if (( ${#WALLPAPERS[@]} == 0 )); then
  echo "No supported wallpaper images found in $WALL_DIR" >&2
  exit 1
fi

mkdir -p "$STATE_DIR" "$(dirname "$COLORS_FILE")" \
  "$(dirname "$ROFI_COLORS")"

# Save the selected theme.
printf '%s\n' "$THEME" > "$STATE_FILE"

# Generate shared accent colors for Polybar and Rofi.
cat <<COLORS > "$COLORS_FILE"
[colors]
background = #E61C1C24
background-alt = #FF292936
foreground = #FFF5F5F7
muted = #FF9898A5
accent = $ACCENT
COLORS

cat <<ROFI > "$ROFI_COLORS"
/* Generated by switch-theme.sh */
* {
    accent: $ACCENT;
    background: #E61C1C24;
    foreground: #FFF5F5F7;
    selected: #FF292936;
}
ROFI

# Apply a random wallpaper from this theme only.
if command -v feh >/dev/null 2>&1; then
  WALLPAPER="${WALLPAPERS[RANDOM % ${#WALLPAPERS[@]}]}"
  if ! feh --no-fehbg --bg-fill "$WALLPAPER"; then
    echo "Could not set wallpaper. Check that X11 is available." >&2
    exit 1
  fi
  printf 'Wallpaper: %s\n' "$WALLPAPER"
else
  echo "feh is not installed; wallpaper was not changed." >&2
fi

printf 'Theme selected: %s (%s)\n' "$THEME" "$ACCENT"
# Restart Polybar so the new theme accent takes effect immediately.
if [[ -x "$BASE/.config/polybar/launch.sh" ]]; then
  "$BASE/.config/polybar/launch.sh"
fi

echo "Theme colors written and Polybar refreshed."
